export const PROVINCES_RISK_DATA: readonly ProvinceRiskRecord[] = RAW_PROVINCE_SEEDS.map((seed) => {
  const hazards = {} as ProvinceRiskRecord['hazards'];
  HAZARD_ORDER.forEach((hazardId, index) => {
    const val = seed.scores[index];
    hazards[hazardId] = {
      score: val,
      applicable: val !== null,
    };
  });

  const exposureIndicators = {} as Record<ExposureIndicatorId, number>;
  E_ORDER.forEach((id, i) => {
    exposureIndicators[id] = seed.e[i];
  });

  const vulnerabilityIndicators = {} as Record<VulnerabilityIndicatorId, number>;
  V_ORDER.forEach((id, i) => {
    vulnerabilityIndicators[id] = seed.v[i];
  });

  const capacityIndicators = {} as Record<CapacityIndicatorId, number>;
  C_ORDER.forEach((id, i) => {
    capacityIndicators[id] = seed.c[i];
  });

  return {
    dopaCode: seed.dopaCode,
    isoCode: `TH-${seed.dopaCode}`,
    nameTh: seed.nameTh,
    nameEn: seed.nameEn,
    shortAliases: seed.aliases,
    region6: seed.region6,
    isBma6: Boolean(seed.isBma6),
    coastalZone: seed.coastalZone,
    geographicNoteTh: seed.geoNote,
    hazards,
    exposureIndicators,
    vulnerabilityIndicators,
    capacityIndicators,
  };
});

export const PROVINCE_BY_CODE: Record<string, ProvinceRiskRecord> = PROVINCES_RISK_DATA.reduce(
  (acc, province) => {
    acc[province.dopaCode] = province;
    return acc;
  },
  {} as Record<string, ProvinceRiskRecord>,
);
